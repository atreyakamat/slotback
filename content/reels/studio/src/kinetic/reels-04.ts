import { El, KCut, KReel, ThemeId } from "./types";

// Series 04 (#117-136): 20 formats, none reused from series 01-03. Hard cuts
// on the beat, a new colour world per cut, and words that swap in place.

type B = KCut["beats"];
const cut = (beats: B, el: El, theme?: ThemeId): KCut => ({ beats, el, theme });
const w = (text: string, beats: B = 2, theme?: ThemeId, kicker?: string) => cut(beats, { t: "word", text, kicker }, theme);
const sw = (before: string, after: string, lead?: string, trail?: string, beats: B = 2, theme?: ThemeId) => cut(beats, { t: "swap", before, after, lead, trail }, theme);
// A run of one-beat word flashes.
const flash = (words: string[], beats: B = 1) => words.map((x) => w(x, beats));

